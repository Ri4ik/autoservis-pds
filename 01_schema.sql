-- AUTOSERVIS / Oracle Database 12c+
-- Upravene: kolekcie VARRAY (vozidlo.historia_km) a NESTED TABLE (servisna_zakazka.kontrolny_zoznam) - clen 3.
-- Spustajte v prazdnej vyhradenej scheme; skript nevykonava DROP.
-- ID 1..999 su vyhradene pre demonstacne data; automaticke ID zacinaju od 1000.

-- ------------------------------------------------------------
-- KOLEKCIE V MODELI (doplnil clen 3 - Danyil Berezhnyi)
--   VOZIDLO.historia_km            VARRAY  - historia stavu tachometra (datum, km, zdroj)
--   SERVISNA_ZAKAZKA.kontrolny_zoznam NESTED TABLE - body kontrolneho zoznamu pri prijati vozidla
-- Typy musia existovat pred tabulkami, ktore ich pouzivaju.
-- ------------------------------------------------------------
CREATE OR REPLACE TYPE t_stav_km AS OBJECT (
 datum DATE,
 km    NUMBER(9),
 zdroj VARCHAR2(10)   -- STK, SERVIS, PREDAJ, ZAKAZNIK
);
/

CREATE OR REPLACE TYPE t_historia_km AS VARRAY(30) OF t_stav_km;
/

CREATE OR REPLACE TYPE t_bod_kontroly AS OBJECT (
 polozka  VARCHAR2(60),
 stav     VARCHAR2(15),  -- OK, CHYBA, NEKONTROLOVANE
 poznamka VARCHAR2(200)
);
/

CREATE OR REPLACE TYPE t_kontrolny_zoznam AS TABLE OF t_bod_kontroly;
/

CREATE TABLE zakaznik (
 id_zakaznik NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 meno VARCHAR2(60) NOT NULL,
 priezvisko VARCHAR2(60) NOT NULL,
 telefon VARCHAR2(25) NOT NULL,
 email VARCHAR2(150),
 datum_registracie DATE DEFAULT SYSDATE NOT NULL,
 CONSTRAINT uq_zakaznik_email UNIQUE (email)
);

CREATE TABLE vozidlo (
 id_vozidlo NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_zakaznik NUMBER NOT NULL,
 vin VARCHAR2(17),
 spz VARCHAR2(15),
 znacka VARCHAR2(60) NOT NULL,
 model VARCHAR2(60) NOT NULL,
 rok_vyroby NUMBER(4),
 historia_km t_historia_km,
 CONSTRAINT fk_vozidlo_zakaznik FOREIGN KEY (id_zakaznik) REFERENCES zakaznik(id_zakaznik),
 CONSTRAINT uq_vozidlo_vin UNIQUE (vin),
 CONSTRAINT uq_vozidlo_spz UNIQUE (spz),
 CONSTRAINT ck_vozidlo_vin CHECK (vin IS NULL OR LENGTH(vin) = 17),
 CONSTRAINT ck_vozidlo_rok CHECK (rok_vyroby BETWEEN 1886 AND 2100)
);

CREATE TABLE zamestnanec (
 id_zamestnanec NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 meno VARCHAR2(60) NOT NULL,
 priezvisko VARCHAR2(60) NOT NULL,
 pozicia VARCHAR2(30) NOT NULL,
 aktivny CHAR(1) DEFAULT 'A' NOT NULL,
 CONSTRAINT ck_zamestnanec_pozicia CHECK (pozicia IN ('MECHANIK','PRIJIMACI_TECHNIK','ADMINISTRATOR')),
 CONSTRAINT ck_zamestnanec_aktivny CHECK (aktivny IN ('A','N'))
);

CREATE TABLE servisna_zakazka (
 id_zakazka NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_vozidlo NUMBER NOT NULL,
 id_zamestnanec NUMBER,
 datum_prijatia DATE DEFAULT SYSDATE NOT NULL,
 datum_dokoncenia DATE,
 datum_odovzdania DATE,
 popis_problemu VARCHAR2(1000) NOT NULL,
 stav VARCHAR2(20) DEFAULT 'PRIJATA' NOT NULL,
 stav_km NUMBER(9),
 kontrolny_zoznam t_kontrolny_zoznam,
 CONSTRAINT fk_zakazka_vozidlo FOREIGN KEY (id_vozidlo) REFERENCES vozidlo(id_vozidlo),
 CONSTRAINT fk_zakazka_zamestnanec FOREIGN KEY (id_zamestnanec) REFERENCES zamestnanec(id_zamestnanec),
 CONSTRAINT ck_zakazka_stav CHECK (stav IN ('PRIJATA','V_OPRAVE','DOKONCENA','ODOVZDANA','ZRUSENA')),
 CONSTRAINT ck_zakazka_km CHECK (stav_km IS NULL OR stav_km >= 0),
 CONSTRAINT ck_zakazka_datum_dok CHECK (datum_dokoncenia IS NULL OR datum_dokoncenia >= datum_prijatia),
 CONSTRAINT ck_zakazka_datum_odov CHECK (datum_odovzdania IS NULL OR (datum_dokoncenia IS NOT NULL AND datum_odovzdania >= datum_dokoncenia)),
 CONSTRAINT ck_zakazka_konzistencia CHECK (
    (stav IN ('PRIJATA','V_OPRAVE','ZRUSENA') AND datum_dokoncenia IS NULL AND datum_odovzdania IS NULL)
 OR (stav = 'DOKONCENA' AND datum_dokoncenia IS NOT NULL AND datum_odovzdania IS NULL)
 OR (stav = 'ODOVZDANA' AND datum_dokoncenia IS NOT NULL AND datum_odovzdania IS NOT NULL))
)
NESTED TABLE kontrolny_zoznam STORE AS servisna_zakazka_kontrola_nt;

-- obmedzenie nad ulozenou vnorenou tabulkou: povolene stavy bodu kontroly
ALTER TABLE servisna_zakazka_kontrola_nt ADD CONSTRAINT ck_kontrola_stav
  CHECK (stav IN ('OK','CHYBA','NEKONTROLOVANE'));

CREATE TABLE servisny_ukon (
 id_ukon NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 nazov VARCHAR2(120) NOT NULL,
 standardna_cena NUMBER(12,2) NOT NULL,
 CONSTRAINT uq_ukon_nazov UNIQUE (nazov),
 CONSTRAINT ck_ukon_cena CHECK (standardna_cena >= 0)
);

CREATE TABLE vykonany_ukon (
 id_vykonany_ukon NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_zakazka NUMBER NOT NULL,
 id_ukon NUMBER NOT NULL,
 id_zamestnanec NUMBER,
 mnozstvo NUMBER(10,2) DEFAULT 1 NOT NULL,
 jednotkova_cena NUMBER(12,2) NOT NULL,
 CONSTRAINT fk_vukon_zakazka FOREIGN KEY (id_zakazka) REFERENCES servisna_zakazka(id_zakazka),
 CONSTRAINT fk_vukon_ukon FOREIGN KEY (id_ukon) REFERENCES servisny_ukon(id_ukon),
 CONSTRAINT fk_vukon_zamestnanec FOREIGN KEY (id_zamestnanec) REFERENCES zamestnanec(id_zamestnanec),
 CONSTRAINT ck_vukon_mnozstvo CHECK (mnozstvo > 0),
 CONSTRAINT ck_vukon_cena CHECK (jednotkova_cena >= 0)
);

CREATE TABLE nahradny_diel (
 id_diel NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 katalogove_cislo VARCHAR2(70) NOT NULL,
 nazov VARCHAR2(150) NOT NULL,
 aktualna_cena NUMBER(12,2) NOT NULL,
 skladom NUMBER(10,2) DEFAULT 0 NOT NULL,
 CONSTRAINT uq_diel_katalog UNIQUE (katalogove_cislo),
 CONSTRAINT ck_diel_cena CHECK (aktualna_cena >= 0),
 CONSTRAINT ck_diel_sklad CHECK (skladom >= 0)
);

CREATE TABLE pouzity_diel (
 id_pouzity_diel NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_zakazka NUMBER NOT NULL,
 id_diel NUMBER NOT NULL,
 mnozstvo NUMBER(10,2) NOT NULL,
 jednotkova_cena NUMBER(12,2) NOT NULL,
 CONSTRAINT fk_pdiel_zakazka FOREIGN KEY (id_zakazka) REFERENCES servisna_zakazka(id_zakazka),
 CONSTRAINT fk_pdiel_diel FOREIGN KEY (id_diel) REFERENCES nahradny_diel(id_diel),
 CONSTRAINT ck_pdiel_mnozstvo CHECK (mnozstvo > 0),
 CONSTRAINT ck_pdiel_cena CHECK (jednotkova_cena >= 0)
);

CREATE TABLE faktura (
 id_faktura NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_zakazka NUMBER NOT NULL,
 cislo_faktury VARCHAR2(35) NOT NULL,
 datum_vystavenia DATE NOT NULL,
 datum_splatnosti DATE NOT NULL,
 celkova_suma NUMBER(12,2) NOT NULL,
 CONSTRAINT fk_faktura_zakazka FOREIGN KEY (id_zakazka) REFERENCES servisna_zakazka(id_zakazka),
 CONSTRAINT uq_faktura_zakazka UNIQUE (id_zakazka),
 CONSTRAINT uq_faktura_cislo UNIQUE (cislo_faktury),
 CONSTRAINT ck_faktura_datum CHECK (datum_splatnosti >= datum_vystavenia),
 CONSTRAINT ck_faktura_suma CHECK (celkova_suma >= 0)
);

CREATE TABLE platba (
 id_platba NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_faktura NUMBER NOT NULL,
 datum_platby DATE NOT NULL,
 suma NUMBER(12,2) NOT NULL,
 sposob VARCHAR2(20) NOT NULL,
 CONSTRAINT fk_platba_faktura FOREIGN KEY (id_faktura) REFERENCES faktura(id_faktura),
 CONSTRAINT ck_platba_suma CHECK (suma > 0),
 CONSTRAINT ck_platba_sposob CHECK (sposob IN ('HOTOVOST','KARTA','PREVOD'))
);

CREATE TABLE priloha (
 id_priloha NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 id_zakazka NUMBER NOT NULL,
 nazov_suboru VARCHAR2(255) NOT NULL,
 mime_typ VARCHAR2(100) NOT NULL,
 obsah BLOB NOT NULL,
 datum_nahratia DATE DEFAULT SYSDATE NOT NULL,
 CONSTRAINT fk_priloha_zakazka FOREIGN KEY (id_zakazka) REFERENCES servisna_zakazka(id_zakazka)
);

-- Indexy na FK: Oracle ich pri definovani cudzieho kluca nevytvori automaticky.
CREATE INDEX ix_vozidlo_zakaznik ON vozidlo(id_zakaznik);
CREATE INDEX ix_zakazka_vozidlo ON servisna_zakazka(id_vozidlo);
CREATE INDEX ix_zakazka_zamestnanec ON servisna_zakazka(id_zamestnanec);
CREATE INDEX ix_vukon_zakazka ON vykonany_ukon(id_zakazka);
CREATE INDEX ix_vukon_ukon ON vykonany_ukon(id_ukon);
CREATE INDEX ix_vukon_zamestnanec ON vykonany_ukon(id_zamestnanec);
CREATE INDEX ix_pdiel_zakazka ON pouzity_diel(id_zakazka);
CREATE INDEX ix_pdiel_diel ON pouzity_diel(id_diel);
CREATE INDEX ix_platba_faktura ON platba(id_faktura);
CREATE INDEX ix_priloha_zakazka ON priloha(id_zakazka);
-- Index na faktura(id_zakazka) uz implicitne pokryva UNIQUE constraint.
