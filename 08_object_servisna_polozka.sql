SET SERVEROUTPUT ON;

-- ============================================================
-- 1. SPECIFIKACIA OBJEKTOVEHO TYPU
-- ============================================================
CREATE OR REPLACE TYPE t_servisna_polozka AS OBJECT (
    id_ukon          NUMBER,
    nazov            VARCHAR2(120),
    jednotkova_cena  NUMBER(12,2),
    mnozstvo         NUMBER(10,2),
    zlava_percent    NUMBER(5,2),

    -- vlastny konstruktor: nova polozka ma automaticky mnozstvo 1 a zlavu 0 %
    CONSTRUCTOR FUNCTION t_servisna_polozka(p_id_ukon NUMBER, p_nazov VARCHAR2, p_cena NUMBER)
        RETURN SELF AS RESULT,

    -- cena x mnozstvo
    MEMBER FUNCTION get_cena RETURN NUMBER,

    -- cena po uplatneni percentualnej zlavy
    MEMBER FUNCTION get_cena_po_zlave RETURN NUMBER,

    -- porovnavanie / triedenie objektov podla vyslednej ceny
    MAP MEMBER FUNCTION tried_podla_ceny RETURN NUMBER
);
/

-- ============================================================
-- 2. TELO OBJEKTOVEHO TYPU
-- ============================================================
CREATE OR REPLACE TYPE BODY t_servisna_polozka AS

    CONSTRUCTOR FUNCTION t_servisna_polozka(p_id_ukon NUMBER, p_nazov VARCHAR2, p_cena NUMBER)
        RETURN SELF AS RESULT
    IS
    BEGIN
        IF p_cena IS NULL OR p_cena < 0 THEN
            RAISE_APPLICATION_ERROR(-20301, 'Jednotkova cena servisnej polozky nemoze byt zaporna ani prazdna.');
        END IF;
        SELF.id_ukon         := p_id_ukon;
        SELF.nazov           := p_nazov;
        SELF.jednotkova_cena := p_cena;
        SELF.mnozstvo        := 1;
        SELF.zlava_percent   := 0;
        RETURN;
    END;

    MEMBER FUNCTION get_cena RETURN NUMBER
    IS
    BEGIN
        RETURN ROUND(SELF.jednotkova_cena * NVL(SELF.mnozstvo, 1), 2);
    END;

    MEMBER FUNCTION get_cena_po_zlave RETURN NUMBER
    IS
    BEGIN
        RETURN ROUND(SELF.get_cena() * (1 - NVL(SELF.zlava_percent, 0) / 100), 2);
    END;

    MAP MEMBER FUNCTION tried_podla_ceny RETURN NUMBER
    IS
    BEGIN
        RETURN SELF.get_cena_po_zlave();
    END;

END;
/

-- ============================================================
-- 3. TABULKA S OBJEKTOVYM ATRIBUTOM
-- ============================================================
-- Rozpis poloziek servisnej zakazky (detail zakazky) - kazda polozka je objekt T_SERVISNA_POLOZKA.
CREATE TABLE servisna_polozka_zakazky (
    id_polozka  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
    id_zakazka  NUMBER NOT NULL,
    polozka     t_servisna_polozka NOT NULL,
    CONSTRAINT fk_polozka_zakazka FOREIGN KEY (id_zakazka) REFERENCES servisna_zakazka(id_zakazka),
    CONSTRAINT ck_polozka_mnozstvo CHECK (polozka.mnozstvo > 0),
    CONSTRAINT ck_polozka_zlava CHECK (polozka.zlava_percent BETWEEN 0 AND 100)
);

CREATE INDEX ix_polozka_zakazka ON servisna_polozka_zakazky(id_zakazka);

