-- ============================================================
-- 5. TESTY - VOLANIE CLENSKYCH FUNKCII CEZ SQL
-- ============================================================
-- OCAKAVANE: 8 poloziek; polozka 3 (brzdy, zlava 10 %) = 85 -> 76.5; polozka 8 (olej 2x, zlava 15 %) = 110 -> 93.5
SELECT p.id_polozka,
       p.id_zakazka,
       p.polozka.nazov              AS nazov,
       p.polozka.jednotkova_cena    AS jednotkova_cena,
       p.polozka.mnozstvo           AS mnozstvo,
       p.polozka.zlava_percent      AS zlava_percent,
       p.polozka.get_cena()         AS cena,
       p.polozka.get_cena_po_zlave() AS cena_po_zlave
FROM servisna_polozka_zakazky p
ORDER BY p.id_polozka;

-- Detail servisnej zakazky (report 11): suma poloziek pred a po zlave za kazdu zakazku
SELECT p.id_zakazka,
       COUNT(*)                            AS pocet_poloziek,
       SUM(p.polozka.get_cena())           AS suma_bez_zlavy,
       SUM(p.polozka.get_cena_po_zlave())  AS suma_po_zlave,
       SUM(p.polozka.get_cena()) - SUM(p.polozka.get_cena_po_zlave()) AS usetrene
FROM servisna_polozka_zakazky p
GROUP BY p.id_zakazka
ORDER BY p.id_zakazka;

-- ============================================================
-- 6. TESTY - TRIEDENIE A POROVNAVANIE (MAP MEMBER FUNCTION)
-- ============================================================
-- ORDER BY objektoveho stlpca pouzije MAP funkciu -> triedenie podla vyslednej ceny po zlave
SELECT p.id_polozka, p.polozka.nazov AS nazov, p.polozka.get_cena_po_zlave() AS cena_po_zlave
FROM servisna_polozka_zakazky p
ORDER BY p.polozka DESC;

-- Porovnanie objektov operatorom > (tiez cez MAP): polozky drahsie ako 50 EUR
SELECT p.id_polozka, p.polozka.nazov AS nazov, p.polozka.get_cena_po_zlave() AS cena_po_zlave
FROM servisna_polozka_zakazky p
WHERE p.polozka > t_servisna_polozka(NULL, 'porovnavacia polozka', 50)
ORDER BY p.polozka;

-- Najdrahsia polozka v kazdej zakazke (ROW_NUMBER usporiadany podla objektu -> MAP)
-- OCAKAVANE: 1 olej 55, 2 brzdy 76.5, 3 olej 93.5, 4 diagnostika 35, 5 prezutie 40
SELECT id_zakazka, nazov, cena_po_zlave
FROM (
    SELECT p.id_zakazka,
           p.polozka.nazov AS nazov,
           p.polozka.get_cena_po_zlave() AS cena_po_zlave,
           ROW_NUMBER() OVER (PARTITION BY p.id_zakazka ORDER BY p.polozka DESC) AS poradie
    FROM servisna_polozka_zakazky p
)
WHERE poradie = 1
ORDER BY id_zakazka;

-- ============================================================
-- 7. TEST V PL/SQL - konstruktor, metody, porovnanie, osetrenie vynimky
-- ============================================================
DECLARE
    v_a t_servisna_polozka := t_servisna_polozka(4, 'Prezutie pneumatik', 40);
    v_b t_servisna_polozka := t_servisna_polozka(3, 'Vymena brzdovych dosticiek', 85);
    v_chybna t_servisna_polozka;
BEGIN
    DBMS_OUTPUT.PUT_LINE('A: ' || v_a.nazov || ', mnozstvo=' || v_a.mnozstvo || ', zlava=' || v_a.zlava_percent
                         || '%, cena=' || v_a.get_cena() || ', po zlave=' || v_a.get_cena_po_zlave());
    v_b.zlava_percent := 50;
    DBMS_OUTPUT.PUT_LINE('B: ' || v_b.nazov || ', cena=' || v_b.get_cena() || ', po zlave=' || v_b.get_cena_po_zlave());
    IF v_a > v_b THEN
        DBMS_OUTPUT.PUT_LINE('Drahsia je A');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Drahsia je B');
    END IF;

    v_chybna := t_servisna_polozka(99, 'Chybna polozka', -10);
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Odchytena vynimka: ' || SQLERRM);
END;
/

