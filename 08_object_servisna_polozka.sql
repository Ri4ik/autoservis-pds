--   * vlastny konstruktor (mnozstvo = 1, zlava = 0 %)
--   * 2 clenske funkcie: GET_CENA(), GET_CENA_PO_ZLAVE()
--   * MAP MEMBER FUNCTION na porovnavanie a triedenie podla vyslednej ceny
--   * pouzitie objektu ako atributu tabulky SERVISNA_POLOZKA_ZAKAZKY
